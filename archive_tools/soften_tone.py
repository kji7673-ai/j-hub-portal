def apply_replacements(file_path):
    with open(file_path, 'r', encoding='utf-8') as f:
        text = f.read()
    
    for old, new in replacements:
        text = text.replace(old, new)
        
    with open(file_path, 'w', encoding='utf-8') as f:
        f.write(text)

